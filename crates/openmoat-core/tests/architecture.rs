//! Architecture invariants for the trusted core (`docs/ARCHITECTURE.md` §1).
//!
//! `openmoat-core` must stay pure: no internal crates, no I/O or runtime crates.
//! A wasm32 build catches most OS calls; `std::fs`/`std::env` still
//! compile there, so the source scan below is what actually enforces purity.

use std::fs;
use std::path::Path;

const ALLOWED_DEPENDENCIES: &[&str] = &["serde", "serde-saphyr", "globset", "thiserror"];

#[test]
fn core_depends_only_on_pure_crates() {
    let manifest = Path::new(env!("CARGO_MANIFEST_DIR")).join("Cargo.toml");
    let text = fs::read_to_string(&manifest).unwrap();
    let deps = section(&text, "[dependencies]");
    for name in deps {
        assert!(
            ALLOWED_DEPENDENCIES.contains(&name.as_str()),
            "openmoat-core gained dependency `{name}`; the core must stay free of I/O and internal crates"
        );
    }
}

#[test]
fn core_forbids_unsafe() {
    let lib = Path::new(env!("CARGO_MANIFEST_DIR")).join("src/lib.rs");
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../Cargo.toml");
    let combined = fs::read_to_string(lib).unwrap() + &fs::read_to_string(root).unwrap();
    assert!(
        combined.contains("unsafe_code = \"forbid\"") || combined.contains("forbid(unsafe_code)"),
        "unsafe must be forbidden for openmoat-core"
    );
}

/// Invariant 4 (fail closed): `openmoat guard` turns a panic into a deny with
/// `catch_unwind`, which only works while panics unwind. `panic = "abort"` in a
/// profile would make every panic exit 134, which no host blocks on (they block
/// on exit 2), so the call would run. No profile of the workspace may set it.
#[test]
fn no_profile_aborts_on_panic() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../Cargo.toml");
    let text = fs::read_to_string(root).unwrap();
    let mut profile = None;
    for line in text.lines().map(str::trim) {
        if line.starts_with('[') {
            profile = line.strip_prefix("[profile.").map(str::to_owned);
            continue;
        }
        let key = line.split('=').next().unwrap_or_default().trim();
        if let Some(name) = &profile {
            assert!(
                key != "panic",
                "[profile.{name} sets `panic`: the guard's panic-to-deny needs unwinding"
            );
        }
    }
    assert!(
        text.contains("[profile.release]"),
        "the release profile was found"
    );
}

/// AGENTS §4: the most lines of code a source file may have. It is a ratchet:
/// lower it when every file fits, never raise it.
const MAX_CODE_LINES: usize = 500;
const _: () = assert!(MAX_CODE_LINES <= 500, "the size cap only goes down");

/// Directories whose `.rs` files are data, not code: captured payloads,
/// expected outputs and snapshots.
const NOT_CODE_DIRS: &[&str] = &["fixtures", "golden", "goldens", "snapshots"];

/// AGENTS §4: no code file in any crate, sources or tests, has more than
/// [`MAX_CODE_LINES`] lines of code. Blank lines and comment lines are not
/// counted, so doc comments never push a file over; neither are files under
/// [`NOT_CODE_DIRS`] or files marked `@generated` (only `.rs` files are read,
/// so generated docs and JSON or YAML fixtures never count).
#[test]
fn no_file_in_any_crate_exceeds_the_size_budget() {
    let crates = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
    let mut offenders = Vec::new();
    for entry in fs::read_dir(&crates).unwrap() {
        let krate = entry.unwrap().path();
        for dir in ["src", "tests"] {
            let root = krate.join(dir);
            if !root.is_dir() {
                continue;
            }
            visit(&root, &mut |path| {
                let in_data_dir = path
                    .components()
                    .any(|c| NOT_CODE_DIRS.contains(&c.as_os_str().to_string_lossy().as_ref()));
                let text = fs::read_to_string(path).unwrap();
                if in_data_dir || is_generated(&text) {
                    return;
                }
                let lines = code_lines(&text);
                if lines > MAX_CODE_LINES {
                    offenders.push(format!("{} ({lines} lines of code)", path.display()));
                }
            });
        }
    }
    assert!(
        offenders.is_empty(),
        "split these files:\n{}",
        offenders.join("\n")
    );
}

#[test]
fn the_size_budget_counts_code_lines_only() {
    let text = "//! Module doc.\n\n/// Item doc.\nfn f() {\n    // note\n    g();\n}\n";
    assert_eq!(code_lines(text), 3);
    let over = "x();\n".repeat(MAX_CODE_LINES + 1);
    assert!(
        code_lines(&over) > MAX_CODE_LINES,
        "a long code file must still fail"
    );
    assert!(is_generated("// @generated by a tool\nfn f() {}\n"));
    assert!(!is_generated(&format!("{over}// @generated\n")));
}

/// Lines that are neither blank nor only a `//` comment.
fn code_lines(text: &str) -> usize {
    text.lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with("//"))
        .count()
}

/// Whether a comment in a file's first five lines says a tool wrote it.
fn is_generated(text: &str) -> bool {
    text.lines()
        .take(5)
        .any(|l| l.trim_start().starts_with("//") && l.contains("@generated"))
}

/// AGENTS §4: a module with children is `foo.rs` + `foo/`, never `foo/mod.rs`,
/// and no module is wired to a file through a `path` attribute.
#[test]
fn modules_use_one_file_style() {
    let crates = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
    let mut offenders = Vec::new();
    for entry in fs::read_dir(&crates).unwrap() {
        let krate = entry.unwrap().path();
        for dir in ["src", "tests"] {
            let root = krate.join(dir);
            if !root.is_dir() {
                continue;
            }
            visit(&root, &mut |path| {
                if path.file_name().is_some_and(|n| n == "mod.rs") {
                    offenders.push(format!("{} is a mod.rs", path.display()));
                }
                for (n, line) in fs::read_to_string(path).unwrap().lines().enumerate() {
                    let code = line.trim_start();
                    // `path = "…"` alone on a line is a multi-line `cfg_attr`.
                    if code.starts_with("#[path")
                        || code.starts_with("path = \"")
                        || (code.starts_with("#[cfg_attr(") && code.contains("path = \""))
                    {
                        offenders.push(format!("{}:{} sets a module path", path.display(), n + 1));
                    }
                }
            });
        }
    }
    assert!(
        offenders.is_empty(),
        "use `foo.rs` + `foo/` and `cfg` on the `mod` line:\n{}",
        offenders.join("\n")
    );
}

/// The only files of the workspace that may lift the `unsafe_code` lint, which
/// is `forbid` everywhere else. Shrink only: a new entry needs an ADR, and an
/// entry whose file no longer names the lint fails, so it must be removed.
/// `openmoat-wasm`'s exports need a fixed symbol name (ADR-046); `openmoat run`
/// marks the descriptors it inherited close-on-exec by number (ADR-088).
const UNSAFE_ALLOWED: &[&str] = &[
    "openmoat-wasm/src/lib.rs",
    "openmoat-cli/src/commands/run/inherited.rs",
    "openmoat-cli/src/state_acl/windows/win32.rs",
];

/// Where a crate's Rust code lives: every `.rs` file below these, and `build.rs`.
const CODE_DIRS: &[&str] = &["src", "tests", "benches", "examples"];

/// `unsafe` is held in three places:
/// - the workspace's `unsafe_code` is `forbid`, and every crate either takes
///   the workspace's lints or sets `unsafe_code` itself: `forbid`, or `deny`
///   only in a crate that owns a file of [`UNSAFE_ALLOWED`];
/// - no other file names the lint or opens an `unsafe` block (under `deny`,
///   each use needs an `#[expect(unsafe_code)]`, so the name finds them all;
///   under `forbid` nothing compiles);
/// - each listed file still names it.
#[test]
fn unsafe_stays_in_the_listed_files() {
    // This file names the lint in its checks; its crate is `forbid`, held below.
    const THIS: &str = "openmoat-core/tests/architecture.rs";
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../Cargo.toml");
    let workspace = entries(&fs::read_to_string(root).unwrap(), "[workspace.lints.rust]");
    let mut offenders = Vec::new();
    if lint_level(&workspace) != Some("forbid") {
        offenders.push("the workspace's `unsafe_code` is not `forbid`".to_owned());
    }
    let crates = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
    let mut named = Vec::new();
    for entry in fs::read_dir(&crates).unwrap() {
        let krate = entry.unwrap().path();
        let manifest = krate.join("Cargo.toml");
        if !manifest.is_file() {
            continue;
        }
        let name = krate.file_name().unwrap().to_string_lossy().into_owned();
        let prefix = format!("{name}/");
        let owns_listed = UNSAFE_ALLOWED.iter().any(|f| f.starts_with(&prefix));
        let toml = fs::read_to_string(&manifest).unwrap();
        let inherits = entries(&toml, "[lints]")
            .iter()
            .any(|(key, value)| key == "workspace" && value == "true");
        let own = entries(&toml, "[lints.rust]");
        let level = if inherits {
            Some("forbid")
        } else {
            lint_level(&own)
        };
        match level {
            Some("forbid") => {}
            Some("deny") if owns_listed => {}
            other => offenders.push(format!("{name}: `unsafe_code` is {other:?}")),
        }
        let mut files = Vec::new();
        for dir in CODE_DIRS {
            let dir = krate.join(dir);
            if dir.is_dir() {
                visit(&dir, &mut |path| files.push(path.to_path_buf()));
            }
        }
        files.extend(Some(krate.join("build.rs")).filter(|p| p.is_file()));
        for path in files {
            let rel = path.strip_prefix(&krate).unwrap().components();
            let rel: Vec<_> = rel.map(|c| c.as_os_str().to_string_lossy()).collect();
            let key = format!("{name}/{}", rel.join("/"));
            let hits = unsafe_lines(&fs::read_to_string(&path).unwrap());
            if UNSAFE_ALLOWED.contains(&key.as_str()) {
                if !hits.is_empty() {
                    named.push(key);
                }
            } else if key != THIS {
                offenders.extend(hits.iter().map(|n| format!("{key}:{n}")));
            }
        }
    }
    for listed in UNSAFE_ALLOWED {
        if !named.iter().any(|k| k == listed) {
            offenders.push(format!(
                "{listed} is listed but no longer names `unsafe_code`: remove it"
            ));
        }
    }
    assert!(
        offenders.is_empty(),
        "`unsafe` outside what is listed:\n{}",
        offenders.join("\n")
    );
}

/// The numbers of the lines of `text` whose code (before any `//`) names the
/// lint or opens an `unsafe` block.
fn unsafe_lines(text: &str) -> Vec<usize> {
    text.lines()
        .enumerate()
        .filter(|(_, line)| {
            let code = line.split("//").next().unwrap_or("");
            code.contains("unsafe_code") || code.contains("unsafe {")
        })
        .map(|(n, _)| n + 1)
        .collect()
}

/// The `unsafe_code` level among `entries`, unquoted.
fn lint_level(entries: &[(String, String)]) -> Option<&str> {
    entries
        .iter()
        .find(|(key, _)| key == "unsafe_code")
        .map(|(_, value)| value.trim_matches('"'))
}

/// The `key = value` lines of the TOML table `header`, comments dropped.
fn entries(toml: &str, header: &str) -> Vec<(String, String)> {
    toml.lines()
        .skip_while(|l| l.trim() != header)
        .skip(1)
        .take_while(|l| !l.trim_start().starts_with('['))
        .filter_map(|l| {
            let line = l.split('#').next()?;
            let (key, value) = line.split_once('=')?;
            Some((key.trim().to_owned(), value.trim().to_owned()))
        })
        .collect()
}

const FORBIDDEN_IN_CORE: &[&str] = &[
    "std::fs",
    "std::env",
    "std::process",
    "std::net",
    "std::io::std",
    "println!",
    "eprintln!",
    "dbg!",
];

#[test]
fn core_sources_do_no_io() {
    let src = Path::new(env!("CARGO_MANIFEST_DIR")).join("src");
    let mut offenders = Vec::new();
    visit(&src, &mut |path| {
        for (n, line) in fs::read_to_string(path).unwrap().lines().enumerate() {
            let code = line.split("//").next().unwrap_or("");
            if let Some(hit) = FORBIDDEN_IN_CORE.iter().find(|t| code.contains(*t)) {
                offenders.push(format!("{}:{} uses {hit}", path.display(), n + 1));
            }
        }
    });
    assert!(
        offenders.is_empty(),
        "openmoat-core must stay free of I/O; inject it from the CLI through a trait:\n{}",
        offenders.join("\n")
    );
}

fn section(toml: &str, header: &str) -> Vec<String> {
    toml.lines()
        .skip_while(|l| l.trim() != header)
        .skip(1)
        .take_while(|l| !l.trim_start().starts_with('['))
        .filter_map(|l| {
            let key = l.split(['=', '.']).next()?.trim();
            (!key.is_empty() && !key.starts_with('#')).then(|| key.to_owned())
        })
        .collect()
}

fn visit(dir: &Path, f: &mut dyn FnMut(&Path)) {
    for entry in fs::read_dir(dir).unwrap() {
        let path = entry.unwrap().path();
        if path.is_dir() {
            visit(&path, f);
        } else if path.extension().is_some_and(|e| e == "rs") {
            f(&path);
        }
    }
}
