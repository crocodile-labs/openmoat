//! Codex backend: a `[permissions.moat]` profile in `config.toml` (ADR-018).
//!
//! Key names are those of codex-cli 0.160 (`PermissionProfileToml` in
//! `codex-rs/config/src/permissions_toml.rs`). The profile does not extend
//! `:workspace`, which reads the whole disk (it let `npm test` read `~/.ssh`
//! in the spike); it grants exactly the IR's reads. What the generator relies
//! on, verified with `codex sandbox -P` on macOS:
//! - a path maps to `read`, `write` or `deny`; a glob may only `deny`, and only
//!   at the top level or under `:workspace_roots` (not under `:tmpdir`);
//! - `deny` wins over an enclosing `read` (`~/.cargo` leaves
//!   `~/.cargo/credentials.toml` denied); nothing re-allows inside a deny;
//! - `.git` in a workspace root stays read-only whatever the profile says;
//! - `network.domains` is enforced by Codex's own proxy (`features.network_proxy`),
//!   which `codex sandbox` starts on an ephemeral loopback port; the profile
//!   then allows commands no other connection (`curl --noproxy '*'` fails);
//! - that proxy hands allowed connections to an upstream proxy only when Codex
//!   itself runs with `HTTP(S)_PROXY` and `allow_upstream_proxy` is on; no
//!   `config.toml` key names the upstream (`network-proxy/src/upstream.rs`).
//!
//! On Linux, bubblewrap can only hide paths that exist, so before each command
//! Codex lists every file below a deny glob's literal prefix with `rg --files`
//! and refuses to start the command when ripgrep reports any error
//! (`expand_unreadable_globs_with_ripgrep` in `linux-sandbox/src/bwrap.rs`).
//! System directories hold root-only directories (`/etc/ssl/private`, the
//! `systemd-private-*` directories in `/tmp`), so `**/` denies are repeated only
//! below the roots inside the home directory, which the user can list.
//!
//! Those listed files are all a glob hides there: a command may create a match
//! that is missing when it starts (#377). A missing literal deny path inside a
//! writable root is mounted over with an empty read-only file at its first
//! missing component (`append_unreadable_root_args`), so on Linux each `**/<name>`
//! deny is also written as `<name>` in the workspace roots (see [`deny_names`]),
//! and a directory the policy denies writing itself (`.claude`, `.cursor`) is
//! made read-only there, so a command cannot plant `.claude/settings.local.json`:
//! mounting over a missing `.claude` withholds nothing the policy allows. Codex
//! removes those mount points after the command.

